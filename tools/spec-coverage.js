#!/usr/bin/env node
/**
 * Spec coverage report for the three sciences.
 *
 *   node tools/spec-coverage.js
 *
 * Reads data/{biology,chemistry,physics}-syllabus.json (the specRef on each
 * subtopic) and data/spec/{subject}.md (the spec headings, made locally by
 * tools/extract-spec.py — not committed). Writes tools/spec-coverage.md:
 *   (a) every 4.x.y section with the subtopics that map to it
 *   (b) every 4.x.y section with no subtopic
 *   (c) any subtopic with an empty or missing specRef
 *   (d) any specRef that is not a section in the spec
 *   (e) every deepest-level section with no subtopic (finer than (b))
 * A specRef deeper than 4.x.y (e.g. 4.6.1.2) counts towards its 4.x.y.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SUBJECTS = ['biology', 'chemistry', 'physics'];
const OUT = path.join(__dirname, 'spec-coverage.md');

const byNum = (a, b) => {
  const x = a.split('.').map(Number), y = b.split('.').map(Number);
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    if (x[i] === undefined) return -1;
    if (y[i] === undefined) return 1;
    if (x[i] !== y[i]) return x[i] - y[i];
  }
  return 0;
};
const three = n => n.split('.').slice(0, 3).join('.');

function specSections(subject) {
  const file = path.join(ROOT, 'data', 'spec', subject + '.md');
  if (!fs.existsSync(file)) {
    console.error(`Missing ${path.relative(ROOT, file)} — run: python tools/extract-spec.py`);
    process.exit(1);
  }
  const titles = new Map();
  for (const m of fs.readFileSync(file, 'utf8').matchAll(/^#{2,6} (4(?:\.\d+)+) (.*)$/gm)) {
    titles.set(m[1], m[2].trim());
  }
  return titles;
}

function subtopics(subject) {
  const syl = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', subject + '-syllabus.json'), 'utf8'));
  const out = [];
  for (const [code, t] of Object.entries(syl.topics)) {
    for (const st of t.subtopics) out.push({ id: st.id, topic: code, specRef: st.specRef });
  }
  return out;
}

const lines = [];
const summary = [];
lines.push('# Spec coverage — sciences');
lines.push('');
lines.push('Generated by `node tools/spec-coverage.js` from the `specRef` on each subtopic in');
lines.push('`data/{subject}-syllabus.json` and the spec headings in `data/spec/{subject}.md`');
lines.push('(local only — see data/spec/MANIFEST.md). A specRef deeper than 4.x.y counts');
lines.push('towards its 4.x.y section. "Mapped" means at least one subtopic points into the');
lines.push('section; it does not mean every sentence of the section is taught.');
lines.push('');

const parts = { a: [], b: [], c: [], d: [], e: [] };

for (const subject of SUBJECTS) {
  const titles = specSections(subject);
  const all = [...titles.keys()];
  const level3 = all.filter(n => n.split('.').length === 3).sort(byNum);
  const hasChildren = n => all.some(m => m.startsWith(n + '.'));
  const leaves = all.filter(n => n.split('.').length >= 3 && !hasChildren(n)).sort(byNum);
  const subs = subtopics(subject);

  const at3 = new Map(level3.map(n => [n, []]));
  const atLeaf = new Map(leaves.map(n => [n, []]));
  const empty = [], bad = [];
  for (const st of subs) {
    if (!Array.isArray(st.specRef) || st.specRef.length === 0) { empty.push(st.id); continue; }
    for (const ref of st.specRef) {
      if (!titles.has(ref)) { bad.push(`${st.id}: ${ref}`); continue; }
      const k = three(ref);
      if (at3.has(k) && !at3.get(k).includes(st.id)) at3.get(k).push(st.id);
      // a ref covers every leaf at or under it
      for (const leaf of leaves) {
        if ((leaf === ref || leaf.startsWith(ref + '.')) && !atLeaf.get(leaf).includes(st.id)) atLeaf.get(leaf).push(st.id);
      }
    }
  }

  const name = subject[0].toUpperCase() + subject.slice(1);
  const mapped = level3.filter(n => at3.get(n).length).length;
  const leafMapped = leaves.filter(n => atLeaf.get(n).length).length;
  summary.push(`- ${name}: ${mapped} of ${level3.length} sections (4.x.y) mapped; ` +
    `${leafMapped} of ${leaves.length} deepest-level sections mapped; ${subs.length} subtopics`);

  parts.a.push(`### ${name}`, '');
  for (const n of level3) {
    const ids = at3.get(n);
    parts.a.push(`- ${n} ${titles.get(n)} — ${ids.length ? ids.join(', ') : '**none**'}`);
  }
  parts.a.push('');

  parts.b.push(`### ${name}`, '');
  const none = level3.filter(n => !at3.get(n).length);
  if (none.length) for (const n of none) parts.b.push(`- ${n} ${titles.get(n)}`);
  else parts.b.push('- none');
  parts.b.push('');

  parts.c.push(`### ${name}`, '');
  parts.c.push(...(empty.length ? empty.map(id => `- ${id}`) : ['- none']), '');

  parts.d.push(`### ${name}`, '');
  parts.d.push(...(bad.length ? bad.map(b => `- ${b}`) : ['- none']), '');

  parts.e.push(`### ${name}`, '');
  const leafNone = leaves.filter(n => !atLeaf.get(n).length);
  parts.e.push(...(leafNone.length ? leafNone.map(n => `- ${n} ${titles.get(n)}`) : ['- none']), '');
}

lines.push('## Summary', '', ...summary, '');
lines.push('## (a) Every 4.x.y section and the subtopics that map to it', '', ...parts.a);
lines.push('## (b) 4.x.y sections with no subtopic', '', ...parts.b);
lines.push('## (c) Subtopics with an empty specRef', '', ...parts.c);
lines.push('## (d) specRefs that are not sections in the spec', '', ...parts.d);
lines.push('## (e) Deepest-level sections with no subtopic', '', ...parts.e);

fs.writeFileSync(OUT, lines.join('\n').replace(/\n+$/, '\n'));
console.log(summary.join('\n'));
console.log('Wrote ' + path.relative(ROOT, OUT));
